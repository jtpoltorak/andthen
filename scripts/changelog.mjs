// Writes CHANGELOG.md from the app's release notes, so the notes people read in
// the app ("What's new") and the ones in the repo are always the same.
//   npm run changelog          rewrite CHANGELOG.md
//   npm run changelog:check    fail if CHANGELOG.md is out of date (CI runs this)
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { RELEASES } from '../apps/web/src/app/about/release-notes.ts';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const file = join(root, 'CHANGELOG.md');

const lines = [
  "# What's new in AndThen",
  '',
  '<!-- Generated by scripts/changelog.mjs from apps/web/src/app/about/release-notes.ts. Edit that file, then run `npm run changelog`. -->',
  '',
];
for (const release of RELEASES) {
  lines.push(`## ${release.version} (${release.date})`, '');
  if (release.title) lines.push(release.title, '');
  for (const note of release.notes) lines.push(`- ${note}`);
  lines.push('');
}
const text = lines.join('\n');

if (process.argv.includes('--check')) {
  let current = '';
  try {
    current = readFileSync(file, 'utf8');
  } catch {}
  if (current !== text) {
    console.error('CHANGELOG.md is out of date. Run `npm run changelog` and commit the result.');
    process.exit(1);
  }
  console.log('CHANGELOG.md is up to date.');
} else {
  writeFileSync(file, text);
  console.log('Wrote CHANGELOG.md');
}
