// Writes the app's version, build date and commit into a small TypeScript file
// the web app imports, so the app never bundles the whole package.json.
// Runs before every web build, serve and test (see apps/web/package.json).
// The version itself lives in exactly one place: the root package.json.
import { execSync } from 'node:child_process';
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const { version } = JSON.parse(readFileSync(join(root, 'package.json'), 'utf8'));

/** Railway and GitHub Actions pass the commit in; locally, ask git. Docker builds have neither. */
function commit() {
  const fromEnv = process.env.RAILWAY_GIT_COMMIT_SHA || process.env.GITHUB_SHA;
  if (fromEnv) return fromEnv.slice(0, 7);
  try {
    return execSync('git rev-parse --short=7 HEAD', {
      cwd: root,
      stdio: ['ignore', 'pipe', 'ignore'],
    })
      .toString()
      .trim();
  } catch {
    return '';
  }
}

const out = join(root, 'apps/web/src/app/about/version.generated.ts');
writeFileSync(
  out,
  `// Generated by scripts/stamp-version.mjs. Do not edit; change the root package.json instead.
export const APP_VERSION = ${JSON.stringify(version)};
export const BUILD_DATE = ${JSON.stringify(new Date().toISOString().slice(0, 10))};
export const BUILD_COMMIT = ${JSON.stringify(commit())};
`,
);
